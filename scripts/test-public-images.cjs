const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ts=require('typescript');
require.extensions['.ts']=(mod,filename)=>{
 const code=fs.readFileSync(filename,'utf8');
 const output=ts.transpileModule(code,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText;
 mod._compile(output,filename);
};
const {publicDataFromStore}=require('../lib/public-site-data.ts');
const {importClinicCatalog}=require('../lib/catalog-import.ts');
const {profiles}=require('../lib/clinic-data.ts');
const store={users:[{username:'admin',password_hash:'redacted'}],tables:{},updated_at:''};
importClinicCatalog(store,'team');
const person=store.tables.specialists.find(x=>x.name_ar===profiles[0].nameAr);
assert.ok(person,'official specialist seeded');
const oldPhoto=person.image_url;
const publishedPhoto='https://images.example.com/approved-portrait.webp';
person.image_url=publishedPhoto;
person.photo_fit='cover';person.photo_position_x=140;person.photo_position_y=-10;
// An older duplicated ID must never supersede a newer approved portrait, even if stored last.
store.tables.specialists.push({...person,image_url:oldPhoto,updated_at:'2000-01-01T00:00:00.000Z'});
const specialty=store.tables.specialties[0];
const specialtyImage='https://images.example.com/approved-service.webp';
specialty.image_url=specialtyImage;
const logo='https://images.example.com/approved-logo.png';
const hero='https://images.example.com/approved-hero.png';
store.tables.site_settings.push({id:'visual-1',key:'site_visuals',is_public:true,value:{logo,hero,heroFit:'contain',heroPositionX:150,heroPositionY:-20}});
store.tables.site_settings.push({id:'about-1',key:'about_content',is_public:true,value:{headingAr:'النبذة المحدّثة من لوحة الإدارة',headingEn:'Updated About heading',bodyAr:'نبذة جديدة من Neon',bodyEn:'New published copy'}});
store.tables.blog_posts=[{id:'article1',title_ar:'مقال',status:'published',cover_image_url:'https://images.example.com/article.webp'},
 {id:'draft1',title_ar:'مسودة',status:'draft',cover_image_url:'https://images.example.com/draft.webp'}];
const first=publicDataFromStore(store);
assert.equal(first.about.headingAr,'النبذة المحدّثة من لوحة الإدارة','published About content available on first server render');
assert.equal(first.about.bodyEn,'New published copy','English About copy is taken from CMS');
assert.equal(first.about.cardTitleAr,'نهتم بالإنسان قبل الحالة','missing About fields use approved defaults');
assert.equal(first.people.find(x=>x.nameAr===person.name_ar).photo,publishedPhoto,'approved portrait resolved for first render');
assert.notEqual(first.people.find(x=>x.nameAr===person.name_ar).photo,oldPhoto,'bundled portrait is not displayed first');
assert.equal(first.people.find(x=>x.nameAr===person.name_ar).photoFit,'cover','per-specialist photo fit is published');
assert.equal(first.people.find(x=>x.nameAr===person.name_ar).photoPositionX,100,'portrait X clamped');
assert.equal(first.people.find(x=>x.nameAr===person.name_ar).photoPositionY,0,'portrait Y clamped');
assert.equal(first.services.find(x=>x.slug===specialty.slug).image,specialtyImage);
assert.equal(first.visuals.logo,logo);
assert.equal(first.visuals.hero,hero);
assert.equal(first.visuals.heroFit,'contain','hero fit is loaded from published settings');
assert.equal(first.visuals.heroPositionX,100,'hero horizontal focal point is clamped');
assert.equal(first.visuals.heroPositionY,0,'hero vertical focal point is clamped');
assert.equal(first.articles.length,1,'drafts remain hidden');
assert.equal(JSON.stringify(first).includes('password_hash'),false,'never send password hashes');
person.is_published=false;
const hidden=publicDataFromStore(store);
assert.equal(hidden.people.some(x=>x.nameAr===person.name_ar),false,'unpublished specialists remain hidden');
const client=fs.readFileSync(path.join(__dirname,'../components/public-site-client.tsx'),'utf8');
assert.equal(client.includes('useClinicCatalog()'),false,'do not hydrate bundled photos first');
assert.equal(client.includes('useSiteVisuals()'),false,'do not hydrate bundled visuals first');
assert.equal(client.includes('usePublicContent()'),false,'do not fetch published content after hydration');
const wrapper=fs.readFileSync(path.join(__dirname,'../components/public-site.tsx'),'utf8');
assert.ok(wrapper.includes('await connection()'),'public pages are server-rendered dynamically');
assert.ok(wrapper.includes('initialData={initialData}'),'server provides approved images before hydration');
assert.ok(fs.readFileSync(path.join(__dirname,'../components/booking-form.tsx'),'utf8').includes('people:Profile[],services:Specialty[]'));
assert.ok(client.includes("encodeURIComponent(p.slug)"),'specialist booking link prefills slug');
assert.ok(client.includes("photoPositionX ?? 50"),'portrait framing rendered in public pages');
console.log('Public first-render image and duplicate-record regression checks passed');
