const assert = require('node:assert/strict');
const path = require('node:path');
const ts = require('typescript');
require.extensions['.ts'] = (mod, filename) => {
 const source = require('node:fs').readFileSync(filename, 'utf8');
 const out = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText;
 mod._compile(out,filename);
};
const {importClinicCatalog}=require('../lib/catalog-import.ts');
const {isAllowedImageUrl}=require('../lib/image-urls.ts');
const {profiles,specialties}=require('../lib/clinic-data.ts');
const {CATALOG_SETTING_KEY}=require('../lib/catalog.ts');
const initial=()=>({users:[],tables:{},updated_at:''});
let checks=0;
function expect(a,b,msg){assert.deepEqual(a,b,msg);checks++}
const store=initial();
const first=importClinicCatalog(store,'team');
expect(first.addedProfiles,profiles.length,'import all professionals');
expect(first.addedSpecialties,specialties.length,'auto-import specialties');
expect(first.addedLinks,profiles.length,'connect specialists to services');
expect(store.tables.specialists.length,10,'10 real records');
expect(store.tables.specialties.length,7,'7 real records');
expect(store.tables.site_settings[0].value,{specialties:true,team:true},'activate atomically');
const h=store.tables.specialists.find(r=>r.name_ar==='هبه الحبيب');
assert.ok(h,'real specialist record');checks++;
h.image_url='/api/media/media/12345678-1234-1234-1234-123456789abc.webp';
h.bio_ar='Custom user edited biography';
expect(importClinicCatalog(store,'team').addedProfiles,0,'idempotent import');
expect(store.tables.specialists.find(r=>r.id===h.id).image_url,h.image_url,'retain uploaded photo');
expect(store.tables.specialists.find(r=>r.id===h.id).bio_ar,'Custom user edited biography','retain edited biography');
expect(store.tables.specialist_specialties.length,profiles.length,'no duplicate relationships');
const partial=initial();
partial.tables.specialists=[{...store.tables.specialists[0]}];
partial.tables.specialties=[{...store.tables.specialties[0]}];
const repaired=importClinicCatalog(partial,'team');
expect(repaired.addedProfiles,9,'repair interrupted team import');
expect(repaired.addedSpecialties,6,'repair interrupted specialty import');
expect(partial.tables.specialists.length,10,'full repaired catalog');
const onlyServices=initial();
const special=importClinicCatalog(onlyServices,'specialties');
expect(special.addedSpecialties,7,'import services only');
expect(special.addedProfiles,0,'services do not create team');
expect(onlyServices.tables.site_settings[0].value.team,undefined,'not activate team before imported');
expect(isAllowedImageUrl('/assets/team/heba-alhabib.webp'),true,'existing asset');
expect(isAllowedImageUrl('/api/media/media/12345678-1234-1234-1234-123456789abc.webp'),true,'new private image URL');
expect(isAllowedImageUrl('https://images.example.com/clinic.png'),true,'https image');
expect(isAllowedImageUrl('javascript:alert(1)'),false,'reject JS URL');
expect(isAllowedImageUrl('/api/media/../../other'),false,'reject traversals');
expect(isAllowedImageUrl('http://example.com/unsafe.png'),false,'reject insecure HTTP');
console.log(`Catalog import & photo URLs: ${checks} checks passed`);
